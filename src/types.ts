export type PrimaryVehicleType = 'car' | 'bike' | 'cycle' | 'other';
export type VehicleType = PrimaryVehicleType | 'scooter' | 'auto_rickshaw' | 'bicycle';

export interface VehicleConfig {
  id: VehicleType;
  label: string;
  sublabel: string;
  icon: string;
  description: string;
  riskMultiplier: number; // multiplier for hazard severity
  vulnerabilityText: string;
}

export type HazardType = 
  | 'pothole'
  | 'crack'
  | 'waterlogging'
  | 'broken_road'
  | 'debris'
  | 'broken_signal'
  | 'other';

export type SeverityLevel = 'CRITICAL' | 'HIGH' | 'MODERATE' | 'LOW';

export interface RoadHazard {
  id: string | number;
  title: string;
  type: HazardType;
  severity: SeverityLevel;
  lat: number;
  lng: number;
  roadName: string;
  firstReportedDate: string;
  lastConfirmedDate?: string;
  confirmationsCount: number;
  confidence: number; // Final confidence (0 - 100% or 0 - 1.0)
  aiConfidence?: number; // 0 - 100% generated by AI model
  manualConfidence?: number; // 0 - 100% entered by user/reporter based on evidence
  finalConfidence?: number; // 0 - 100% calculated
  photoAvailable?: boolean;
  gpsVerified?: boolean;
  depthCm: number;
  sizeM?: number;
  description?: string;
  imageUrl?: string;
  reportedBy?: string;
  verified?: boolean;
  distanceFromRoute?: number; // meters from route corridor
  nearestRoutePoint?: [number, number]; // [lat, lon] nearest point on route polyline
  isDemo?: boolean; // clearly marks simulated demo records for presentation/testing
  source?: string;
}

export interface NavigationStep {
  instruction: string;
  distanceMeters: number;
  streetName: string;
  action: 'turn-left' | 'turn-right' | 'straight' | 'u-turn' | 'arrive';
  lat: number;
  lng: number;
}

export interface RouteOption {
  id: 'safer' | 'fastest' | string;
  name: string;
  tagline: string;
  distanceKm: number;
  durationMinutes: number;
  safetyScore: number; // 0 - 100
  hazardCount: number;
  criticalCount?: number;
  highCount?: number;
  moderateCount?: number;
  lowCount?: number;
  hazards: RoadHazard[];
  color: string;
  waypoints: [number, number][]; // [lat, lng] coordinates
  steps: NavigationStep[];
  isRecommended?: boolean;
  recommendationReason?: string;
}

export interface UserProfile {
  name: string;
  email: string;
  phone?: string;
  avatarUrl?: string;
  vehicle: VehicleType;
  isGuest?: boolean;
  reportsCount: number;
  confirmedCount: number;
  resolvedCount: number;
  contributionPoints: number;
  badges: Array<{
    id: string;
    title: string;
    icon: string;
    description: string;
    earned: boolean;
  }>;
}

export interface NotificationItem {
  id: string;
  type: 'critical_hazard' | 'high_hazard' | 'moderate_hazard' | 'low_hazard' | 'route_warning' | 'safer_route' | 'report_verified';
  title: string;
  message: string;
  timestamp: string;
  unread: boolean;
  severity: SeverityLevel;
  hazardId?: string | number;
  roadName?: string;
  distanceAheadMeters?: number;
}

export interface DestinationPlace {
  id: string | number;
  name: string;
  address: string;
  category?: string;
  lat: number;
  lng: number;
  distance?: string;
  icon?: string;
}
